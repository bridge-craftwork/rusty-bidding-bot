#!/usr/bin/env python3
"""Tabulate the range probe: each robot's call by position, shape class and
HCP, the HCP span of each call, and pairwise agreement.

    probes/range-probe/analyze.py [--out probes/range-probe/TABLES.md]

Reads `data/<position>.jsonl` and the robots' calls beside it:
`.ours.jsonl`, `.brill.jsonl`, `.wb5.jsonl`, and BBA from the grid run
(`.rbb-cache/grids/<position>/grid.json`, copied to `data/<position>.bba.json`).
"""
import argparse
import json
import os
import re
from collections import Counter, defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "data")
ROBOTS = ["ours", "bba", "brill", "wb5"]
NAMES = {"ours": "Rusty", "bba": "BBA", "brill": "Brill", "wb5": "WBridge5"}
POSITIONS = {"resp1S": "1♠ (P) ?", "resp1H": "1♥ (P) ?", "reb1D1S": "1♦ (P) 1♠ (P) ?"}
SUIT = {"♠": "S", "♥": "H", "♦": "D", "♣": "C"}


def norm(c):
    if c is None:
        return None
    if isinstance(c, dict) and "Bid" in c:
        b = c["Bid"]
        return f"{b['level']}" + {"Clubs": "C", "Diamonds": "D", "Hearts": "H", "Spades": "S",
                                  "NoTrump": "N"}[b["strain"]]
    if c in ("Double", "Redouble"):
        return {"Double": "X", "Redouble": "XX"}[c]
    c = str(c).strip()
    for k, v in SUIT.items():
        c = c.replace(k, v)
    u = c.upper()
    if u in ("PASS", "P", "--"):
        return "P"
    if u in ("X", "DBL", "DB"):
        return "X"
    if u in ("XX", "RDBL", "RD"):
        return "XX"
    u = re.sub(r"NT$", "N", u)
    return u


def load(pos):
    rows = [json.loads(l) for l in open(os.path.join(DATA, f"{pos}.jsonl"))]
    calls = {r: {} for r in ROBOTS}
    for r in ("ours", "brill", "wb5"):
        p = os.path.join(DATA, f"{pos}.{r}.jsonl")
        if os.path.exists(p):
            for l in open(p):
                d = json.loads(l)
                if d.get("call") is not None:
                    calls[r][d["id"]] = norm(d["call"])
    p = os.path.join(DATA, f"{pos}.bba.json")
    if os.path.exists(p):
        g = json.load(open(p))
        for row in g["rows"]:
            c = row["cells"][0].get("bba")
            if c is not None:
                calls["bba"][row["label"]] = norm(c)
    return rows, calls


def cell(cs):
    if not cs:
        return "·"
    c = Counter(cs)
    return " ".join((f"{n}×{k}" if n > 1 else k) for k, n in c.most_common())


def spans(rows, calls, robot, cls=None):
    """call -> (min HCP, max HCP, count) over the class's hands."""
    by = defaultdict(list)
    for r in rows:
        if cls and r["class"] != cls:
            continue
        c = calls[robot].get(r["id"])
        if c:
            by[c].append(r["hcp"])
    return {c: (min(h), max(h), len(h)) for c, h in by.items()}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(HERE, "TABLES.md"))
    a = ap.parse_args()
    out = ["# Range probe: the tables", "",
           "Generated by `probes/range-probe/analyze.py`. Each cell lists the calls the robot "
           "made with the hands of that shape class and HCP (four hands a cell, `3×1N` = three "
           "of them bid 1NT). `·`: no answer (WBridge5 did not reach the position).", ""]
    for pos, title in POSITIONS.items():
        if not os.path.exists(os.path.join(DATA, f"{pos}.jsonl")):
            continue
        rows, calls = load(pos)
        have = [r for r in ROBOTS if calls[r]]
        out += [f"## {pos}: {title}", ""]
        # agreement
        out += ["Pairwise agreement (same call, hands both answered):", "",
                "| | " + " | ".join(NAMES[r] for r in have) + " |",
                "|---|" + "---|" * len(have)]
        for x in have:
            cells = []
            for y in have:
                both = [r["id"] for r in rows if r["id"] in calls[x] and r["id"] in calls[y]]
                same = sum(calls[x][i] == calls[y][i] for i in both)
                cells.append(f"{100 * same / len(both):.0f}% ({len(both)})" if both else "–")
            out.append(f"| {NAMES[x]} | " + " | ".join(cells) + " |")
        out.append("")
        classes = list(dict.fromkeys(r["class"] for r in rows))
        for cls in classes:
            sub = [r for r in rows if r["class"] == cls]
            out += [f"### {pos} / {cls}", "",
                    "| HCP | " + " | ".join(NAMES[r] for r in have) + " |",
                    "|---|" + "---|" * len(have)]
            for h in sorted({r["hcp"] for r in sub}):
                hs = [r for r in sub if r["hcp"] == h]
                out.append(f"| {h} | " + " | ".join(
                    cell([calls[rb][r["id"]] for r in hs if r["id"] in calls[rb]]) for rb in have) + " |")
            out += ["", "HCP span of each call (min-max, hands):", ""]
            for rb in have:
                sp = spans(rows, calls, rb, cls)
                txt = ", ".join(f"{c} {lo}-{hi} ({n})" if lo != hi else f"{c} {lo} ({n})"
                                for c, (lo, hi, n) in sorted(sp.items(), key=lambda kv: (kv[1][0], kv[1][1])))
                out.append(f"- {NAMES[rb]}: {txt}")
            out.append("")
    with open(a.out, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
